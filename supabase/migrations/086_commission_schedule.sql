  id      bigint generated always as identity primary key,
  carrier text not null,
  type    text,
  product text not null,
  tier    integer not null,
  pct     numeric,
  unique (carrier, product, tier)
);

create index if not exists commission_schedule_carrier_idx on commission_schedule(carrier);
create index if not exists commission_schedule_lookup_idx on commission_schedule(carrier, product, tier);

