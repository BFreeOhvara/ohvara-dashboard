-- Migration 086: real Compensation Grid data (Prompt 370)
--
-- Normalized long format (one row per carrier+product+tier) rather than 20
-- wide tier columns, so the real lookup query for a policy's exact
-- commission (`where carrier = X and product = Y and tier = 70`) is trivial
-- and this table can later be joined against `policies` once policies
-- capture their exact carrier+product (flagged in Prompt 370, not built yet).
--
-- Seeded from Brayden's own Eterna (IMO platform) Compensation Grid export,
-- vault: brain/commission-schedule-tier70.csv. `pct` is null wherever the
-- source has no rate at that tier (e.g. F&G ExecuDex 61-99, and the 3
-- carriers below awaiting real data) — never invented.
--
-- Baltimore Life, Aflac, Chubb are real carriers (already in the `carriers`
-- table) but have zero contract data yet — seeded as a single placeholder
-- row each (`product` names the carrier they're waiting on) with `pct` null
-- across all 20 tiers, so the Compensation Grid page can still show them in
-- the carrier filter with dashes, matching this app's existing
-- missing-data convention, rather than omitting them entirely.
--
-- Augustar and SBLI were present in the raw Eterna export but Brayden
-- confirmed neither is a real Ohvara carrier ("toss them") — not seeded.

