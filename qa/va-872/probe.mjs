// P872 — functional probe (no screenshots): the phone dock opens, X minimises mid-call without hanging up, the page
// column makes room, nothing overflows; Training unlock order and a check pass.  node qa/va-872/probe.mjs <base>
import { chromium } from 'playwright'
const BASE = process.argv[2] || 'http://localhost:4872'
const b = await chromium.launch()
const out = []
const ok = (c, m) => out.push(`${c ? 'PASS' : 'FAIL'} ${m}`)
for (const [w, h] of [[1440, 900], [390, 844]]) {
  const p = await b.newPage({ viewport: { width: w, height: h } })
  await p.route(/supabase\.co|\/functions\/v1\//, r => r.abort('failed'))
  const errs = []; p.on('pageerror', e => errs.push(e.message))
  await p.goto(`${BASE}/template/fulfillment/leads`, { waitUntil: 'networkidle' })
  await p.evaluate(() => localStorage.clear())
  await p.reload({ waitUntil: 'networkidle' })
  await p.waitForTimeout(600)
  const dock = await p.locator('.fs-dock-btn').boundingBox()
  const cw = await p.evaluate(() => document.querySelector('.fs-dock-layer').getBoundingClientRect().width)
  ok(dock && Math.abs(cw - (dock.x + dock.width) - (w < 1000 ? 14 : 16)) < 2, `${w} round phone button bottom-right ${JSON.stringify(dock)}`)
  if (w >= 1000) {
    const col = await p.locator('.fx-col').boundingBox()
    ok(col.x + col.width <= dock.x - 8, `${w} column clears the button (col right ${Math.round(col.x + col.width)}, button ${Math.round(dock.x)})`)
  }
  await p.click('.fs-dock-btn')
  await p.waitForSelector('.fs-phone')
  await p.waitForTimeout(450)
  const panel = await p.locator('.fs-phone').boundingBox()
  ok(w >= 1000 ? Math.round(cw - panel.x - panel.width) === 16 && Math.round(h - panel.y - panel.height) === 16 : panel.width >= cw - 21, `${w} panel docked ${JSON.stringify(panel)}`)
  if (w >= 1000) {
    await p.waitForTimeout(400)
    const col = await p.locator('.fx-col').boundingBox()
    ok(col.x + col.width <= panel.x, `${w} page column makes room for the open panel (col right ${Math.round(col.x + col.width)}, panel left ${Math.round(panel.x)})`)
    ok(await p.locator('.fx-scrim').count() === 0, `${w} no scrim: page stays usable`)
  }
  await p.fill('.fs-ph-entry input', '5125550161')
  await p.click('.fs-ph-dial:has-text("Call")')
  await p.waitForSelector('.fs-ph-timer')
  await p.waitForTimeout(2100)
  await p.click('.fs-phone .fx-x')
  await p.waitForTimeout(400)
  ok(await p.locator('.fs-phone').count() === 0 && await p.locator('.fs-dock-pill.is-live').count() === 1, `${w} X during a call shows the pill, panel gone`)
  const t1 = await p.locator('.fs-dock-pill small').textContent()
  await p.waitForTimeout(1600)
  const t2 = await p.locator('.fs-dock-pill small').textContent()
  ok(t1 !== t2, `${w} timer keeps running while minimised (${t1} -> ${t2})`)
  await p.click('.fs-dock-pill')
  await p.waitForSelector('.fs-ph-timer')
  ok(await p.locator('.fs-ctl.is-end').count() === 1, `${w} reopened on the same live call (Hang up there)`)
  await p.keyboard.press('Escape') // focus is inside the panel: Esc minimises, still no hang up
  await p.waitForTimeout(350)
  ok(await p.locator('.fs-dock-pill.is-live').count() === 1, `${w} Esc minimises, call still live`)
  await p.click('.fs-dock-pill'); await p.waitForSelector('.fs-ctl.is-end')
  await p.click('.fs-ctl.is-end')
  ok(await p.locator('text=How did it go?').count() > 0, `${w} red button hangs up -> result step`)
  await p.click('.fs-phone .fx-x'); await p.waitForTimeout(350)
  ok(await p.locator('.fs-dock-pill:not(.is-live)').count() === 1, `${w} unsaved result keeps a pill`)
  await p.click('.fs-dock-pill'); await p.click('.fs-ph-acts .tp-btn:has-text("Skip")'); await p.click('.fs-phone .fx-x'); await p.waitForTimeout(350)
  ok(await p.locator('.fs-dock-btn').count() === 1, `${w} back to the round button`)
  // A ring (from the + menu's Live call) opens the panel by itself; X while ringing badges the button.
  if (w >= 1000) await p.click('.fx-rplus'); else await p.click('.fx-btab.is-plus')
  await p.click('[role=menuitem]:has-text("Live call")')
  await p.waitForSelector('.fs-ph-ring')
  ok(true, `${w} ring opens the panel`)
  await p.click('.fs-phone .fx-x'); await p.waitForTimeout(350)
  ok(await p.locator('.fs-dock-btn.is-ringing .fx-badge').count() === 1, `${w} ringing badge on the closed button`)
  await p.click('.fs-dock-btn'); await p.click('button:has-text("Not now")'); await p.waitForTimeout(350)
  ok(await p.locator('.fs-dock-btn.is-missed .fx-badge').textContent() === '1', `${w} Not now -> 1 missed`)
  const over = await p.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  ok(!over, `${w} no sideways scroll`)
  // Training
  await p.goto(`${BASE}/template/fulfillment/training`, { waitUntil: 'networkidle' })
  await p.waitForTimeout(500)
  const rows = await p.locator('.tr-row').evaluateAll(els => els.map(e => e.className.match(/is-(\w+)/)?.[1]))
  ok(rows.slice(0, 4).every(r => r === 'passed') && rows[4] === 'next' && rows.slice(5).every(r => r === 'locked'), `${w} sample Maya: 4 passed, lesson 5 next, rest locked (${rows.join(',')})`)
  await p.fill('.tr-find input', 'someone says stop')
  ok((await p.locator('.tr-hits b').first().textContent()) === 'Opt-outs and do-not-call', `${w} How do I search`)
  await p.goto(`${BASE}/template/fulfillment/training/inbound`, { waitUntil: 'networkidle' })
  await p.click('button:has-text("Take the check")')
  const n = await p.locator('.tr-qs > li').count()
  for (let i = 0; i < n; i++) await p.locator('.tr-qs > li').nth(i).locator('.tr-opt').nth(1).click() // answer 2nd option each
  await p.click('button:has-text("Check my answers")')
  const res = await p.locator('.tr-result h2').textContent()
  ok(res === 'Passed', `${w} check scored and passed (${res}, ${await p.locator('.tr-res-n').textContent()})`)
  await p.goto(`${BASE}/template/fulfillment/training`, { waitUntil: 'networkidle' })
  const rows2 = await p.locator('.tr-row').evaluateAll(els => els.map(e => e.className.match(/is-(\w+)/)?.[1]))
  ok(rows2[4] === 'passed' && rows2[5] === 'next', `${w} passing lesson 5 opened lesson 6`)
  await p.goto(`${BASE}/template/fulfillment/leads`, { waitUntil: 'networkidle' })
  ok(await p.locator('.fx-tools .tr-help').count() === 1, `${w} ? on the Queue`)
  ok(!errs.length, `${w} no page errors ${errs.join(' | ')}`)
  await p.close()
}
await b.close()
console.log(out.join('\n'))
