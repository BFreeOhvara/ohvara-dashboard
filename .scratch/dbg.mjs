import { chromium } from 'playwright'
const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } }); const page = await ctx.newPage()
await page.addInitScript(() => localStorage.setItem('ohvara-theme','light'))
await page.route('**/functions/v1/self-signup', async r => { const body = JSON.parse(r.request().postData()||'{}'); console.log('req', body.action); r.fulfill({ status:200, contentType:'application/json', headers:{'access-control-allow-origin':'*'}, body: JSON.stringify(body.action==='status'?{open:true}:{ok:true}) }) })
await page.route('**/auth/v1/**', r => r.fulfill({ status:400, contentType:'application/json', headers:{'access-control-allow-origin':'*'}, body:'{"code":"invalid_credentials","error_description":"Invalid login credentials"}' }))
await page.goto('http://localhost:5388/signup'); await page.waitForSelector('form.su-card')
await page.fill('input[name=name]','Alex Rivera'); await page.fill('input[name=email]','a@b.co'); await page.fill('input[name=new-password]','abcdefg1')
await page.locator('.su-cbrow').click()
console.log('checked', await page.locator('.su-cbrow input').isChecked())
await page.getByRole('button',{name:/Create account/}).click()
await page.waitForTimeout(6000)
console.log(await page.locator('.su-card').innerText())
await page.screenshot({ path: '.scratch/shots/dbg.png', fullPage: true })
await b.close()
